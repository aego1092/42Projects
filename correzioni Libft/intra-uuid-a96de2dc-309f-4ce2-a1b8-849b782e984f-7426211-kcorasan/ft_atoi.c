#include "libft.h"

int	ft_atoi(const char *nptr)
{
	long long	sign;
	long long	out;

	sign = 1;
	out = 0;
	while (*nptr == ' ' || (*nptr >= '\t' && *nptr <= '\r'))
		nptr++;
	if (*nptr == '+' || *nptr == '-')
	{
		if (*nptr == '-')
			sign = -1;
		nptr++;
	}
	while (*nptr >= '0' && *nptr <= '9')
	{
		out = out * 10 + (*nptr - '0');
		nptr++;
	}
	return ((int)(out * sign));
}
